class CatchUpTests(unittest.TestCase):
    def test_matches_headset_servo(self):
        rp, rq, ap, aq, cmd, expected = (torch.tensor([row[k] for row in GOLDEN], dtype=torch.float64) for k in range(6))
        command = torch.zeros(len(GOLDEN), 35)
        command[:, [0, 1, 5]] = cmd.float(); command[:, 6:] = 7.
        out = servo(command, rp, rq, ap, aq)
        torch.testing.assert_close(out[:, [0, 1, 5]], expected.float(), atol=2e-6, rtol=0)
        self.assertTrue(torch.equal(out[:, [2, 3, 4]], command[:, [2, 3, 4]]))
        self.assertTrue(torch.equal(out[:, 6:], command[:, 6:]))

    def test_reset_frame_and_disabled_envs_keep_command(self):
        state = CatchUp(4, 'cpu', .5, seed=3)
        state.enabled[:] = torch.tensor([True, True, False, False])
        q = torch.tensor([[0., 0, 0, 1]]*4)
        robot = torch.zeros(4, 3); ref = torch.tensor([[1., 0, 0]]*4)
        command = torch.zeros(4, 35)
        state.fresh[:] = torch.tensor([True, False, True, False])
        out = state.apply(command, ref, q, robot, q)
        torch.testing.assert_close(out[:, 0], torch.tensor([0., .4, 0., 0.]))
        self.assertFalse(state.fresh.any())
        torch.testing.assert_close(state.stats, torch.tensor([1., .4, 1.], dtype=torch.float64))

    def test_reset_draw_fraction(self):
        state = CatchUp(20000, 'cpu', .75, seed=5)
        state.reset(torch.arange(20000))
        self.assertAlmostEqual(state.enabled.float().mean().item(), .75, delta=.01)
        self.assertTrue(state.fresh.all())


